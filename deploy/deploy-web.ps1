<#
.SYNOPSIS
    Builds the Compose web app and deploys it to Firebase Hosting.

.DESCRIPTION
    Writes the API address into config.js inside the release bundle, because Hosting and
    Cloud Run live on different domains and the app cannot infer one from the other.

    The address comes from ApiBaseUrl in release.config.ps1, or from the Cloud Run service
    when that is left blank.

.EXAMPLE
    ./deploy/deploy-web.ps1 -DryRun
    Builds nothing and prints what would be deployed.
#>
[CmdletBinding()]
param(
    # Print commands instead of running them.
    [switch]$DryRun,
    # Reuse the bundle already in the distribution directory.
    [switch]$SkipBuild,
    # Deploy to a temporary preview URL instead of the live site.
    [string]$PreviewChannel
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$repoRoot = Split-Path -Parent $PSScriptRoot
$configPath = Join-Path $PSScriptRoot "release.config.ps1"

if (-not (Test-Path $configPath)) {
    throw "Missing $configPath. Copy release.config.ps1.example and fill in your project."
}
. $configPath

$distDir = Join-Path $repoRoot "app/webApp/build/dist/wasmJs/productionExecutable"

function Invoke-Step {
    param(
        [Parameter(Mandatory)][string]$Description,
        [Parameter(Mandatory)][string[]]$Command
    )

    Write-Host ""
    Write-Host "==> $Description" -ForegroundColor Cyan
    Write-Host "    $($Command -join ' ')" -ForegroundColor DarkGray

    if ($DryRun) { return }

    & $Command[0] @($Command[1..($Command.Length - 1)])
    if ($LASTEXITCODE -ne 0) {
        throw "$Description failed with exit code $LASTEXITCODE"
    }
}

$apiBaseUrl = $ApiBaseUrl
if ([string]::IsNullOrWhiteSpace($apiBaseUrl) -and -not $DryRun) {
    Write-Host "Looking up the Cloud Run URL for $ServiceName..." -ForegroundColor DarkGray
    $apiBaseUrl = (& gcloud run services describe $ServiceName `
        --project=$ProjectId --region=$Region --format="value(status.url)")
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($apiBaseUrl)) {
        throw "Could not resolve the API URL. Deploy the API first, or set ApiBaseUrl in release.config.ps1."
    }
}

if ([string]::IsNullOrWhiteSpace($apiBaseUrl)) {
    Write-Host "API base URL: resolved from Cloud Run at deploy time" -ForegroundColor Green
} else {
    Write-Host "API base URL: $apiBaseUrl" -ForegroundColor Green
}

if (-not $SkipBuild) {
    Invoke-Step -Description "Build the web release bundle" -Command @(
        (Join-Path $repoRoot "gradlew.bat"), ":app:webApp:wasmJsBrowserDistribution", "--console=plain"
    )
}

if (-not $DryRun) {
    if (-not (Test-Path $distDir)) {
        throw "Expected the web bundle at $distDir."
    }

    # Overwrites the placeholder copied from src/webMain/resources.
    $configJs = @(
        "// Generated by deploy/deploy-web.ps1 - do not edit in the build output.",
        "window.KEJASAFE_API_BASE_URL = `"$apiBaseUrl`";"
    ) -join "`n"
    [IO.File]::WriteAllText(
        (Join-Path $distDir "config.js"),
        "$configJs`n",
        (New-Object Text.UTF8Encoding $false)
    )
    Write-Host "Wrote config.js pointing at $apiBaseUrl" -ForegroundColor DarkGray
}

if (-not [string]::IsNullOrWhiteSpace($PreviewChannel)) {
    # Preview channels get their own temporary URL, expire on their own, and never
    # replace what is live.
    $deployCommand = @(
        "firebase", "hosting:channel:deploy", $PreviewChannel,
        "--project", $ProjectId
    )
    if (-not [string]::IsNullOrWhiteSpace($HostingSite)) {
        $deployCommand += @("--only", $HostingSite)
    }
} else {
    $target = if ([string]::IsNullOrWhiteSpace($HostingSite)) { "hosting" } else { "hosting:$HostingSite" }
    $deployCommand = @(
        "firebase", "deploy",
        "--only", $target,
        "--project", $ProjectId
    )
}

Invoke-Step -Description "Deploy to Firebase Hosting" -Command $deployCommand

if ($DryRun) { return }

Write-Host ""
Write-Host "Web app deployed." -ForegroundColor Green
Write-Host "Remember that the API only accepts browser calls from KEJASAFE_ALLOWED_ORIGINS;" -ForegroundColor Yellow
Write-Host "update AllowedOrigins in release.config.ps1 and redeploy the API if the domain changed." -ForegroundColor Yellow
