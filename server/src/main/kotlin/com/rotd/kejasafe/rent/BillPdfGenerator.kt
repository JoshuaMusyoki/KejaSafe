package com.rotd.kejasafe.rent

import com.rotd.kejasafe.RentBill
import java.io.ByteArrayOutputStream
import java.nio.charset.Charset
import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter

/**
 * Minimal PDF writer (no third-party deps) for KejaSafe rent invoices.
 * Generates a single-page Helvetica text PDF suitable for download.
 */
object BillPdfGenerator {
    private val ascii = Charset.forName("ISO-8859-1")
    private val dueFmt = DateTimeFormatter.ofPattern("yyyy-MM-dd")
        .withZone(ZoneId.systemDefault())

    fun render(bill: RentBill, tenantName: String): ByteArray {
        val monthName = monthLabel(bill.month)
        val lines = buildList {
            add("KejaSafe Rent Invoice")
            add("———————————————————————")
            add("Bill ID: ${bill.id}")
            add("Property: ${bill.propertyTitle.ifBlank { bill.propertyId }}")
            add("Tenant: $tenantName")
            add("Period: $monthName ${bill.year}")
            add("Status: ${bill.status.name}")
            add("Due: ${dueFmt.format(Instant.ofEpochMilli(bill.dueDate))}")
            add("")
            add("Charges")
            add("———————————————————————")
            bill.items.forEach { item ->
                val amountLabel = if (item.amount <= 0.0 && item.name.contains("token", ignoreCase = true)) {
                    "TOKEN (prepaid)"
                } else {
                    "KES ${formatAmount(item.amount)}"
                }
                add("${item.name}: $amountLabel")
            }
            add("")
            add("TOTAL DUE: KES ${formatAmount(bill.totalAmount)}")
            if (bill.depositIncluded) {
                add("Includes security deposit (one-time).")
            }
            bill.electricityNote?.let {
                add("")
                add("Note: $it")
            }
            add("")
            add("Pay via KejaSafe Bills • M-PESA supported")
            add("Generated by KejaSafe")
        }

        val content = buildString {
            append("BT\n")
            append("/F1 14 Tf\n")
            append("50 750 Td\n")
            append("16 TL\n")
            lines.forEachIndexed { index, line ->
                if (index == 0) {
                    append("(${escapePdf(line)}) Tj\n")
                } else {
                    append("T*\n(${escapePdf(line)}) Tj\n")
                }
                // Slightly smaller body after title
                if (index == 0) append("/F1 11 Tf\n")
            }
            append("ET\n")
        }
        val contentBytes = content.toByteArray(ascii)

        val objects = mutableListOf<String>()
        // 1 Catalog
        objects += "<< /Type /Catalog /Pages 2 0 R >>"
        // 2 Pages
        objects += "<< /Type /Pages /Kids [3 0 R] /Count 1 >>"
        // 3 Page
        objects += "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] " +
            "/Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>"
        // 4 Content stream
        objects += "<< /Length ${contentBytes.size} >>\nstream\n$content\nendstream"
        // 5 Font
        objects += "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"

        val out = ByteArrayOutputStream()
        fun w(s: String) = out.write(s.toByteArray(ascii))
        w("%PDF-1.4\n")
        val offsets = IntArray(objects.size + 1)
        for (i in objects.indices) {
            offsets[i + 1] = out.size()
            w("${i + 1} 0 obj\n")
            w(objects[i])
            w("\nendobj\n")
        }
        val xrefPos = out.size()
        w("xref\n")
        w("0 ${objects.size + 1}\n")
        w("0000000000 65535 f \n")
        for (i in 1..objects.size) {
            w(offsets[i].toString().padStart(10, '0') + " 00000 n \n")
        }
        w("trailer\n")
        w("<< /Size ${objects.size + 1} /Root 1 0 R >>\n")
        w("startxref\n")
        w("$xrefPos\n")
        w("%%EOF\n")
        return out.toByteArray()
    }

    private fun escapePdf(text: String): String =
        text
            .map { c ->
                when {
                    c == '\\' || c == '(' || c == ')' -> "\\$c"
                    c.code in 32..126 -> c.toString()
                    else -> "?"
                }
            }
            .joinToString("")

    private fun formatAmount(value: Double): String {
        val v = if (value == value.toLong().toDouble()) value.toLong().toString()
        else ((value * 100).toLong() / 100.0).toString()
        return v
    }

    private fun monthLabel(month: Int): String {
        val names = listOf(
            "January", "February", "March", "April", "May", "June",
            "July", "August", "September", "October", "November", "December"
        )
        return names.getOrElse(month - 1) { month.toString() }
    }
}
